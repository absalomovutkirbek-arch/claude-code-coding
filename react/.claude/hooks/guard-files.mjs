/**
 * PreToolUse hook for Edit|Write|MultiEdit.
 *
 * Blocks edits to files Claude must never change:
 *   - .env files (secrets), except .env.example
 *   - node_modules/ (third-party code) and build output (dist/, build/, coverage/)
 *   - lock files (they change only through the package manager)
 *
 * Exit 2 blocks the tool call and shows the message on stderr to Claude.
 * Any other outcome lets the call through.
 */

import { readFileSync } from 'node:fs';
import { basename } from 'node:path';

let input;
try {
  input = JSON.parse(readFileSync(0, 'utf8'));
} catch {
  process.exit(0);
}

const path = input?.tool_input?.file_path;
if (typeof path !== 'string' || path === '') {
  process.exit(0);
}

const normalized = path.replaceAll('\\', '/');
const name = basename(normalized);

function block(message) {
  process.stderr.write(`BLOCKED: ${message}\n`);
  process.exit(2);
}

if (/^\.env(\..+)?$/.test(name) && !/\.(example|dist|sample)$/.test(name)) {
  block(`${name} holds secrets and must not be edited by Claude. Ask the developer to change it, or edit .env.example.`);
}

if (/(^|\/)node_modules\//.test(normalized)) {
  block('node_modules/ is third-party code. Change behaviour through configuration, a wrapper or a patch the developer approves.');
}

if (/(^|\/)(dist|build|coverage)\//.test(normalized)) {
  block('This is build output. Change the source file instead.');
}

if (['package-lock.json', 'pnpm-lock.yaml', 'yarn.lock', 'bun.lockb', 'bun.lock'].includes(name)) {
  block(`${name} is generated by the package manager. Ask the developer to run the install command instead.`);
}

process.exit(0);
